import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import { rateLimit } from 'express-rate-limit';
import env from './config/env.js';
import { auth, usuarios } from './routes/auth.routes.js';
import produtos from './routes/produtos.routes.js';
import entradas from './routes/entradas.routes.js';
import vendas from './routes/vendas.routes.js';
import { estoque, dashboard, historico, usuariosProdutos } from './routes/consultas.routes.js';
import { notFound, errorHandler } from './middlewares/error.js';

const app = express();
app.set('trust proxy', 1);
app.use(helmet());
const allowed = env.ALLOWED_ORIGINS.split(',').map((s) => s.trim()).filter(Boolean);
app.use(cors({ origin: (origin, callback) => callback(null, !origin || allowed.length === 0 || allowed.includes(origin)) }));
app.use(express.json({ limit: '200kb' }));
app.use(rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: 'draft-7', legacyHeaders: false }));
app.get('/', (req, res) => res.json({ aplicacao: 'Estoque Senior - AOS', status: 'online', documentacao: '/health' }));
app.get('/health', (req, res) => res.json({ status: 'ok', hora: new Date().toISOString() }));
app.use('/auth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: 'draft-7', legacyHeaders: false }), auth);
app.use('/usuarios', usuariosProdutos, usuarios);
app.use('/produtos', produtos);
app.use('/entradas-mercadoria', entradas);
app.use('/vendas', vendas);
app.use('/estoque', estoque);
app.use('/dashboard', dashboard);
app.use('/historico', historico);
app.use(notFound);
app.use(errorHandler);
export default app;
