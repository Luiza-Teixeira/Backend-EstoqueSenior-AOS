import { Router } from 'express';
import { autenticar } from '../middlewares/auth.js';
import { validarId } from '../utils/errors.js';
import * as acompanhamento from '../services/acompanhamento.service.js';
import * as produtos from '../services/produtos.service.js';
import { AppError } from '../utils/errors.js';
const estoque = Router();
estoque.use(autenticar);
estoque.get('/baixo', async (req, res) => res.json(await acompanhamento.estoqueBaixo(req.usuario.id)));
estoque.get('/', async (req, res) => res.json(await acompanhamento.estoque(req.usuario.id)));
const dashboard = Router();
dashboard.use(autenticar);
dashboard.get('/resumo', async (req, res) => res.json(await acompanhamento.resumo(req.usuario.id)));
const historico = Router();
historico.use(autenticar);
historico.get('/', async (req, res) => res.json(await acompanhamento.historico(req.usuario.id)));
historico.get('/:id', async (req, res) => res.json(await acompanhamento.movimentacao(req.usuario.id, req.params.id)));
const usuariosProdutos = Router();
usuariosProdutos.use(autenticar);
usuariosProdutos.get('/me/produtos', async (req, res) => res.json(await produtos.listar(req.usuario.id)));
export { estoque, dashboard, historico, usuariosProdutos };
